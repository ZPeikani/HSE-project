        DB::transaction(function () use ($checklists, $createdBy): void {
            foreach ($checklists as $data) {
                $checklistId = DB::table('checklists')
                    ->where('title', $data['title'])
                    ->where('category', $data['category'])
                    ->value('id');

                if ($checklistId) {
                    DB::table('checklists')
                        ->where('id', $checklistId)
                        ->update([
                            'description' => $data['description'],
                            'version' => $data['version'],
                            'is_active' => 1,
                            'created_by' => $createdBy,
                            'updated_at' => now(),
                        ]);
                } else {
                    $checklistId = DB::table('checklists')->insertGetId([
                        'title' => $data['title'],
                        'category' => $data['category'],
                        'description' => $data['description'],
                        'version' => $data['version'],
                        'is_active' => 1,
                        'created_by' => $createdBy,
                        'created_at' => now(),
                        'updated_at' => now(),
                    ]);
                }

                foreach ($data['items'] as $sortOrder => $question) {
                    DB::table('checklist_items')->updateOrInsert(
                        [
                            'checklist_id' => $checklistId,
                            'sort_order' => $sortOrder,
                        ],
                        [
                            'question' => $question,
                            'guidance' => null,
                            'weight' => 1,
                            'is_critical' => 0,
                            'updated_at' => now(),
                            'created_at' => now(),
                        ]
                    );
                }
            }
        });
